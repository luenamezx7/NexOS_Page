import sharp from 'sharp';
import { writeFile } from 'node:fs/promises';

// Precompute the optical map once; no canvas, resize rasterization or RAF at runtime.
const size = 128;
const pixels = Buffer.alloc(size * size * 3);
// A broad convex shoulder carries the bend well into the pane, not just its rim.
const rim = distance => distance < .38 ? Math.sin(Math.PI * distance / .38) ** .7 : 0;
for (let y = 0; y < size; y++) {
  for (let x = 0; x < size; x++) {
    const u = x / (size - 1);
    const v = y / (size - 1);
    const index = (y * size + x) * 3;
    pixels[index] = Math.round(128 + 125 * (rim(u) - rim(1 - u)));
    pixels[index + 1] = Math.round(128 + 125 * (rim(v) - rim(1 - v)));
    // Blue is a feathered blur mask: strongest on the perimeter, zero inside.
    const edge = Math.max(0, 1 - Math.min(u, 1 - u, v, 1 - v) / .4);
    pixels[index + 2] = Math.round(255 * edge ** .65);
  }
}
const map = await sharp(pixels, { raw: { width: size, height: size, channels: 3 } })
  .png({ compressionLevel: 9 })
  .toBuffer();
await writeFile('src/lib/hero-glass-map.ts', `// Generated by scripts/generate-hero-glass-map.mjs; no runtime rasterization.\nexport const heroGlassMap = 'data:image/png;base64,${map.toString('base64')}';\n`);
