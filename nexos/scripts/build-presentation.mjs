import { build } from 'esbuild';
import { writeFile, readFile } from 'node:fs/promises';
// Extract the trusted SVG's static paths for synchronous worker rasterization.
const artworkSource = await readFile('src/components/ui/mascot-reveal-artwork.ts', 'utf8');
const artwork = JSON.parse(artworkSource.match(/export const mascotRevealArtwork = (.*);/s)[1]);
const paths = [...artwork.matchAll(/<path\b[^>]*>/g)].filter(([tag]) => !tag.includes('fire-still')).map(([tag]) => {
  const d = tag.match(/\bd="([^"]*)"/)[1];
  const hole = tag.includes('fill="#000"');
  return { d, hole, eye: hole && /^M(?:503|751)/.test(d) };
});
await writeFile('src/components/ui/mascot-reveal-paths.generated.ts',
  '// Generated from mascot-reveal-artwork.ts. Open-eye group translations cancel.\n' +
  `export const mascotPaths = ${JSON.stringify(paths)};\n`);
await build({ entryPoints: ['src/components/ui/presentation-worker.ts'], bundle: true, minify: true,
  format: 'iife', target: 'es2020', outfile: 'public/presentation-worker.js' });
const result = await build({
  entryPoints: ['src/components/ui/presentation-bootstrap-entry.ts'],
  bundle: true, write: false, minify: true, format: 'iife', target: 'es2020',
});
const source = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
await writeFile('src/components/ui/presentation-bootstrap.generated.ts',
  '// Generated by scripts/build-presentation.mjs; initialize WebGL before hydration.\n' +
  `export const presentationBootstrap = ${JSON.stringify(source)};\n`);
